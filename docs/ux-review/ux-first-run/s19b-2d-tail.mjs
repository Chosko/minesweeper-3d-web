import { launch, shot, mode } from './lib.mjs';
const { browser, page } = await launch();
await page.click('#menu-entry-classic-2d'); await page.waitForTimeout(300);
await page.click('#c2d-choice [data-size="custom"]'); await page.fill('#c2d-width', '1'); await page.fill('#c2d-height', '1'); await page.fill('#c2d-mines', '0');
await page.click('#c2d-play'); await page.waitForTimeout(800);
let box = await page.locator('#c2d-board canvas').boundingBox();
await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2); await page.waitForTimeout(2500);
console.log('mode', await mode(page));
await page.click('#r-again'); await page.waitForTimeout(800);
console.log('Play again -> mode', await mode(page), 'hud', await page.evaluate(() => document.querySelector('.ui-overlay-bar')?.innerText.replace(/\n/g,' ')));
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
console.log('Esc (unstarted 2D) -> mode', await mode(page));
await page.click('#p-menu'); await page.waitForTimeout(300);
console.log('Main menu unstarted asks?', await page.evaluate(() => !document.getElementById('pause-confirm').classList.contains('hidden')), 'mode', await mode(page));
await page.click('#menu-entry-classic-2d'); await page.waitForTimeout(300);
console.log('choice focus', await page.evaluate(() => document.activeElement?.id || document.activeElement?.dataset?.size), 'fields', await page.evaluate(() => [document.getElementById('c2d-width').value, document.getElementById('c2d-height').value, document.getElementById('c2d-mines').value]));
await shot(page, '93-c2d-choice-after-custom');
// Beginner game, win not possible quickly; check a Beginner loss then Play again lands directly on a fresh board
await page.click('#c2d-choice [data-size="beginner"]'); await page.click('#c2d-play'); await page.waitForTimeout(600);
box = await page.locator('#c2d-board canvas').boundingBox();
const cell = box.height / 9; const x0 = box.x + (box.width - 9 * cell) / 2;
const cells = []; for (let r = 0; r < 9; r++) for (let c = 0; c < 9; c++) cells.push([c, r]);
cells.sort(() => Math.random() - 0.5);
for (const [c, r] of cells) { await page.mouse.click(x0 + (c + 0.5) * cell, box.y + (r + 0.5) * cell); await page.waitForTimeout(120); if (await mode(page) !== 'classic-2d') break; }
await page.waitForTimeout(300);
await shot(page, '94-c2d-loss-moment');
await page.waitForTimeout(2000);
console.log('mode', await mode(page));
await page.click('#r-again'); await page.waitForTimeout(800);
console.log('Play again (beginner) -> mode', await mode(page), 'hud', await page.evaluate(() => document.querySelector('.ui-overlay-bar')?.innerText.replace(/\n/g,' ')));
await shot(page, '95-c2d-after-play-again');
await page.keyboard.press('Escape'); await page.waitForTimeout(200); await page.click('#p-menu'); await page.waitForTimeout(300);
console.log('menu badges', await page.evaluate(() => [...document.querySelectorAll('#menu button')].map(b => { const badge = [...b.querySelectorAll('*')].find(e => /Last played/.test(e.textContent) && e.children.length === 0); return [b.id, badge ? getComputedStyle(badge).display : 'none']; })));
await shot(page, '96-menu-returning-2d');
await browser.close();
